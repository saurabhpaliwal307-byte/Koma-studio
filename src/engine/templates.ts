function makeArcPoints(
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  steps = 22
) {
  const pts = [];
  for (let i = 0; i <= steps; i++) {
    const a = (i / steps) * Math.PI * 2;
    pts.push({
      x: cx + Math.cos(a) * rx,
      y: cy + Math.sin(a) * ry,
      pressure: 0.7 + 0.25 * Math.sin(a * 2),
    });
  }
  return pts;
}

